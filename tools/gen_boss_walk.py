#!/usr/bin/env python3
"""Bake each boss's Assets/Models/Enemies/Boss/<Boss>/anim/walk.json into src/client/Controllers/BossWalkData/<Variant>.luau.

Per animated joint one flat array, 7 numbers per frame: px py pz qx qy qz qw (Motor6D.Transform, Roblox axes), 3 decimals.
The loop seam (last frame == first) is dropped; joints that never leave the rest pose are skipped.
The three walk.json files use three layouts, normalised here. Run from anywhere: python tools/gen_boss_walk.py
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BOSS = ROOT / "Assets" / "Models" / "Enemies" / "Boss"
OUT = ROOT / "src" / "client" / "Controllers" / "BossWalkData"
SOURCES = {"GoblinKing": "Goblin King", "CursedKing": "Cursed King", "CourtJester": "Court Jester"}


def load(folder: str, clip: str = "walk"):
    d = json.loads((BOSS / folder / "anim" / f"{clip}.json").read_text(encoding="utf-8"))
    if "frames" in d and isinstance(d["frames"], list):  # Cursed King: frames[i][joint] = {p, q(xyzw)}
        n = len(d["frames"])
        joints = {j: [(f[j]["p"], f[j]["q"]) for f in d["frames"]] for j in d["joints"]}
        return d.get("naturalStride"), n, joints
    joints = {}
    for name, j in d["joints"].items():
        if name == "Root":
            continue
        if "quat_wxyz" in j:  # Goblin King: Blender order w,x,y,z
            qs = [[q[1], q[2], q[3], q[0]] for q in j["quat_wxyz"]]
        else:  # Court Jester: x,y,z,w
            qs = j["quat"]
        joints[name] = list(zip(j["pos"], qs))
    stride = d.get("natural_stride_studs_per_cycle", d.get("natural_stride_studs"))
    return stride, len(next(iter(joints.values()))), joints


def num(v: float) -> str:
    s = f"{round(v, 3):.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def main():
    for variant, folder in SOURCES.items():
        stride, count, joints = load(folder)
        frames = count - 1  # frame N == frame 0
        lines = []
        for name, samples in sorted(joints.items()):
            flat, moving = [], False
            for p, q in samples[:frames]:
                n = math.sqrt(sum(c * c for c in q)) or 1
                q = [c / n for c in q]
                moving = moving or max(abs(c) for c in p) > 5e-4 or abs(abs(q[3]) - 1) > 1e-5
                flat += [*p, *q]
            if moving:
                lines.append(f"\t\t{name} = {{ {', '.join(num(v) for v in flat)} }},")
        text = (
            f"-- Generated by tools/gen_boss_walk.py from {folder}/anim/walk.json; do not edit.\n"
            f"return {{\n\tStride = {stride},\n\tFrames = {frames},\n\tJoints = {{\n"
            + "\n".join(lines)
            + "\n\t},\n}\n"
        )
        (OUT / f"{variant}.luau").write_text(text, encoding="utf-8")
        print(variant, stride, frames, len(lines), len(text))


if __name__ == "__main__":
    main()
