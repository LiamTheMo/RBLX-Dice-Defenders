"""Merge the per-die ModelData files from Assets/Models/Dice/_LM/lm_variants.write_modeldata into one file per
rarity, in EpicModelData's layout: shared Layouts, Bodies/Marks, Parts[id], Styles[id]. Packets are copied verbatim
(normalized die space); re-run after regenerating a die. Usage: python tools/merge_rarity_modeldata.py"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DICE = ROOT / "Assets/Models/Dice"
OUT = ROOT / "src/client/Controllers/Dice"
RARITIES = {
    "LegendaryModelData.luau": [
        ("L01", DICE / "Legendary/Variants/L01_Chrono/ChronoModelData.luau"),
        ("L02", DICE / "Legendary/Variants/L02_Forge/ForgeModelData.luau"),
    ],
    "MythicModelData.luau": [("M01", DICE / "Mythic/Variants/M01_Astral/AstralModelData.luau")],
}


def block(text: str, name: str) -> list[str]:
    """Body lines of the top-level `\tname = {` table (tab-indented generator output)."""
    match = re.search(rf"^\t{name} = \{{\n(.*?)^\t\}},\n", text, re.S | re.M)
    if not match:
        raise SystemExit(f"missing {name} block")
    return match.group(1).splitlines()


def merge(out_name: str, sources: list) -> str:
    dies = []
    for style_id, path in sources:
        text = path.read_text(encoding="utf-8")
        dies.append(
            {
                "id": style_id,
                "layouts": block(text, "Layouts"),
                "bodies": block(text, "Bodies"),
                "marks": block(text, "Marks"),
                "parts": block(text, "Parts"),
                "styles": block(text, "Styles"),
            }
        )
        if len(dies[-1]["bodies"]) != 7 or len(dies[-1]["marks"]) != 7:
            raise SystemExit(f"{path}: expected 7 bodies and 7 marks")
    first = dies[0]
    if any(d["layouts"] != first["layouts"] for d in dies):
        raise SystemExit("Layouts differ between dice")
    shared = all(d["bodies"] == first["bodies"] and d["marks"] == first["marks"] for d in dies)

    names = ", ".join(str(p.relative_to(ROOT)).replace("\\", "/") for _, p in sources)
    rows = [f"-- Generated by tools/merge_rarity_modeldata.py from {names}.", "-- stylua: ignore", "return {"]
    rows += ["\tLayouts = {", *first["layouts"], "\t},"]
    if shared:
        rows += ["\tBodies = {", *first["bodies"], "\t},", "\tMarks = {", *first["marks"], "\t},"]
    rows.append("\tParts = {")
    for d in dies:
        rows += [f"\t\t{d['id']} = {{", *("\t" + line for line in d["parts"]), "\t\t},"]
    rows += ["\t},", "\tStyles = {"]
    for d in dies:
        style = d["styles"]
        if not shared:  # per-style Bodies/Marks override the shared tables (Visuals reads style.Bodies first)
            tail = style[-1]
            style = style[:-1]
            for label in ("bodies", "marks"):
                style += [f"\t\t\t{label.title()} = {{", *("\t\t" + line for line in d[label]), "\t\t\t},"]
            style.append(tail)
        rows += style
    rows += ["\t},", "}", ""]
    return "\n".join(rows)


def main() -> None:
    for out_name, sources in RARITIES.items():
        (OUT / out_name).write_text(merge(out_name, sources), encoding="utf-8", newline="\n")
        print("wrote", OUT / out_name)


if __name__ == "__main__":
    sys.exit(main())
