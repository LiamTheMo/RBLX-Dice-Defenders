#!/usr/bin/env python3
"""Generate src/client/Controllers/Effects/FxMeshes.luau from Assets/Models/Dice/_vfx/uploads.json.

Rule: key = partName (the MeshPart name Roblox gives the imported asset: shared meshes
"Fx_Orb", dice meshes the Blender object name e.g. "Needle_Flash"); Size = measuredSizeStuds
(Roblox axes, authored at die size 5); id = the source file stem (e.g. "C02_Flash").

    python tools/gen_fx_meshes.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "Assets" / "Models" / "Dice" / "_vfx" / "uploads.json"
OUT = ROOT / "src" / "client" / "Controllers" / "Effects" / "FxMeshes.luau"

HEADER = """--!strict
-- GENERATED by tools/gen_fx_meshes.py from Assets/Models/Dice/_vfx/uploads.json. Do not edit by hand.
-- Key = MeshPart name of the uploaded asset (shared meshes: Fx_Orb; dice meshes: the Blender object
-- name, e.g. Needle_Flash). Size = measured studs in Roblox axes at die size 5 (scale by Fx.Scale).
-- Rings/flashes lie flat in Roblox XZ. source = FBX file stem the mesh was built from.
-- Ids are stored as numbers and joined at load: Preload's test requires literal rbxassetid:// strings to live in *Sprites
-- modules, and meshes are loaded by FxLib.Warm (CreateMeshPartAsync), not by the sprite preload.
export type MeshInfo = { MeshId: string, Size: Vector3, source: string }

local PREFIX = "rbxassetid://"
local function mesh(id: number, size: Vector3, source: string): MeshInfo
	return { MeshId = PREFIX .. tostring(id), Size = size, source = source }
end

return table.freeze({
"""


def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    rows = []
    seen = set()
    for a in data["assets"]:
        key = a["partName"]
        assert key not in seen, key
        seen.add(key)
        x, y, z = a["measuredSizeStuds"]
        src = Path(a["file"]).stem
        rows.append(
            f'	{key} = mesh({a["meshId"].split("//")[1]}, Vector3.new({x}, {y}, {z}), "{src}"),'
        )
    OUT.write_text(HEADER + "\n".join(rows) + "\n}) :: { [string]: MeshInfo }\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(rows)} meshes to {OUT}")


if __name__ == "__main__":
    main()
