"""Generate src/shared/DiceAssets.luau: the uploaded Model asset id of every die tier, plus the material colours Roblox drops
from the Common/Rare glb files (colour-only materials import grey; atlas-textured dice carry their colour in the texture).
Inputs: Assets/Models/Dice/dice_uploads_new.json (Common/Rare/Secret, tools/upload_dice.py) and the roblox-assets.json of
Epic, Legendary and Mythic. Usage: python tools/build_dice_assets.py"""

import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DICE = ROOT / "Assets/Models/Dice"
OUT = ROOT / "src/shared/DiceAssets.luau"

COMMON = {"C01": "Pebble", "C02": "Needle", "C03": "Hammer", "C04": "Twinshot", "C05": "Longshot", "C06": "Chill", "C07": "Spark"}
RARE = {"R01": "Frost", "R02": "Arc", "R03": "Volley", "R04": "Venom", "R05": "Beacon"}
# type id -> (roblox-assets.json, model name prefix); names are "<prefix>_0<tier>"
UPLOADED = {
    "E01": ("Epic/Variants/roblox-assets.json", "Emberstorm"),
    "E02": ("Epic/Variants/roblox-assets.json", "Mirror"),
    "E03": ("Epic/Variants/roblox-assets.json", "Gravity"),
    "L01": ("Legendary/Variants/roblox-assets.json", "Chrono"),
    "L02": ("Legendary/Variants/roblox-assets.json", "Forge"),
    "M01": ("Mythic/Variants/roblox-assets.json", "Astral"),
}
EDGE = {"C": 2.5, "R": 2.5, "E": 2.5, "L": 4, "M": 4, "S": 4}  # authored die edge in studs (Common..Epic are normalized, x1.6 at runtime)


def to_srgb(linear: float) -> int:
    c = 12.92 * linear if linear <= 0.0031308 else 1.055 * linear ** (1 / 2.4) - 0.055
    return max(0, min(255, round(c * 255)))


def glb_colours(path: Path) -> list[str]:
    """Hex colour of every material slot of every mesh, in primitive order (textured slots are '')."""
    data = path.read_bytes()
    size, _ = struct.unpack_from("<II", data, 12)
    j = json.loads(data[20 : 20 + size])
    out = []
    for mesh in j["meshes"]:
        for prim in mesh["primitives"]:
            pbr = j["materials"][prim["material"]].get("pbrMetallicRoughness", {})
            if "baseColorTexture" in pbr or "baseColorFactor" not in pbr:
                out.append("")
            else:
                r, g, b = pbr["baseColorFactor"][:3]
                out.append("#%02X%02X%02X" % (to_srgb(r), to_srgb(g), to_srgb(b)))
    return out


def main():
    new = json.loads((DICE / "dice_uploads_new.json").read_text())
    ids: dict[str, list[int]] = {}
    colours: dict[str, list[str]] = {}
    for tid, name in COMMON.items():
        ids[tid] = [int(new[f"{tid}_{t}"]) for t in range(1, 8)]
        per = [glb_colours(DICE / f"Common/Variants/{tid}_{name}/exports/{tid}_{name}_T{t}.glb") for t in range(1, 8)]
        colours[tid] = per
    for tid, name in RARE.items():
        ids[tid] = [int(new[f"{tid}_{t}"]) for t in range(1, 8)]
        colours[tid] = [glb_colours(DICE / f"Rare/Variants/{name}/exports/{name}_0{t}.glb") for t in range(1, 8)]
    ids["S01"] = [int(new[f"S01_{t}"]) for t in range(1, 8)]
    for tid, (file, prefix) in UPLOADED.items():
        models = {m["name"]: m["assetId"] for m in json.loads((DICE / file).read_text())["models"]}
        ids[tid] = [int(models[f"{prefix}_0{t}"]) for t in range(1, 8)]

    rows = ["-- Generated by tools/build_dice_assets.py. Uploaded Model asset ids per die tier; Colors holds the glb material colours",
            "-- Roblox drops on import (Common/Rare only, per tier, in mesh-primitive order, '' = textured slot).", "-- stylua: ignore", "return {"]
    rows.append("\tEdge = { C = 2.5, R = 2.5, E = 2.5, L = 4, M = 4, S = 4 },")
    rows.append("\tModels = {")
    for tid in sorted(ids):
        rows.append(f"\t\t{tid} = {{ " + ", ".join(str(i) for i in ids[tid]) + " },")
    rows.append("\t},")
    rows.append("\tColors = {")
    for tid in sorted(colours):
        tiers = ", ".join("{ " + ", ".join(f'"{c}"' for c in t) + " }" for t in colours[tid])
        rows.append(f"\t\t{tid} = {{ {tiers} }},")
    rows.append("\t},")
    rows.append("}")
    OUT.write_text("\n".join(rows) + "\n", encoding="utf-8")
    print("wrote", OUT, len(ids), "dice")


if __name__ == "__main__":
    main()
