#!/usr/bin/env python3
"""Bake each boss's Assets/Models/Enemies/Boss/<Boss>/anim/ability.json into src/client/Controllers/BossAbilityData/<Variant>.luau.

Same layout and normalisation as tools/gen_boss_walk.py (it reuses its loader), but a one-shot clip: every frame is kept
(no loop seam dropped) and Fps is written (the json's "fps" when it has one, else 30; the ability clips are 55 frames at 30 fps
= 1.8 s, the cast frame at 1.0 s). A boss without an ability.json is skipped, and its data module stays absent, which the
client tolerates (no ability animation, VFX hooks still run). Run from anywhere: python tools/gen_boss_ability.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_boss_walk import BOSS, ROOT, SOURCES, joint_lines, load  # noqa: E402

OUT = ROOT / "src" / "client" / "Controllers" / "BossAbilityData"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for variant, folder in SOURCES.items():
        path = BOSS / folder / "anim" / "ability.json"
        if not path.exists():
            print(variant, "no ability.json, skipped")
            continue
        _, frames, joints = load(folder, "ability")
        fps = json.loads(path.read_text(encoding="utf-8")).get("fps", 30)
        lines = joint_lines(joints, frames)
        text = (
            f"-- Generated by tools/gen_boss_ability.py from {folder}/anim/ability.json; do not edit.\n"
            f"return {{\n\tFps = {fps},\n\tFrames = {frames},\n\tJoints = {{\n"
            + "\n".join(lines)
            + "\n\t},\n}\n"
        )
        (OUT / f"{variant}.luau").write_text(text, encoding="utf-8")
        print(variant, fps, frames, len(lines), len(text))


if __name__ == "__main__":
    main()
